// STHGroup: раздельные свободные запасы, резерв, происхождение и места остатков.
const assert = require('assert');
require('../web/core/dbf.js'); require('../web/core/matbase.js'); require('../web/core/sth_stock.js');
const MB = BM.mb, SK = BM.stock, b = SK.fix(MB.empty());
const sheet = MB.addGroup(b, '', 'Листы', 'sheet'), fit = MB.addGroup(b, '', 'Фурнитура', 'fit');
const mat = MB.saveMat(b, Object.assign(MB.defMat(sheet.id), { name: 'ЛДСП Белый', art: 'W980', unit: 'лист', th: 16 })).mat;
const hinge = MB.saveMat(b, Object.assign(MB.defMat(fit.id), { name: 'Петля', unit: 'шт' })).mat;
const origin = { id: 'first', no: '142' }, target = { id: 'second', no: '158' };
SK.move(b, 'in', mat.id, 5, { order: origin }); SK.reserve(b, mat.id, 3, origin);
SK.move(b, 'in', hinge.id, 20);
assert.strictEqual(SK.centerRows(b, 'free', 'sheet')[0].qty, 2);
assert.strictEqual(SK.centerRows(b, 'free', 'fit')[0].qty, 20);
assert.strictEqual(SK.centerRows(b, 'orders', 'all', '142')[0].qty, 3);
assert.strictEqual(SK.centerRows(b, 'orders', 'all', '158').length, 0);
assert.strictEqual(b.stock.docs[0].order, origin.id);
assert.strictEqual(b.stock.docs[0].project, 'Заказ 142');
assert.strictEqual(SK.addRemainder(b, mat.id, 600, 400, -1), null);
assert.strictEqual(SK.addRemainder(b, mat.id, 600, 400, 1.2), null);
assert.strictEqual(SK.addRemainder(b, mat.id, Infinity, 400, 1), null);
assert.strictEqual(SK.addRemainder(b, hinge.id, 600, 400, 1), null);
const a = SK.addRemainder(b, mat.id, 1200, 600, 1, { order: origin.id, no: origin.no, project: 'Заказ №142', cell: 'Б-03', note: 'Без сколов' });
const c = SK.addRemainder(b, mat.id, 850, 450, 1, { cell: 'Б-04' });
SK.setOffCell(b, a.id, 'В-02'); assert.strictEqual(SK.offCell(b, a), 'В-02'); assert.strictEqual(SK.offCell(b, c), 'Б-04');
assert.strictEqual(SK.reserveOff(b, a.id, target), true);
assert.strictEqual(a.originOrder, origin.id); assert.strictEqual(a.project, 'Заказ №142'); assert.strictEqual(a.res, target.id);
assert.strictEqual(SK.reserveOff(b, a.id, origin), false, 'чужой резерв нельзя перезаписать');
assert.strictEqual(SK.offRows(b, '142')[0].id, a.id); assert.strictEqual(SK.offRows(b, '158')[0].id, a.id);
assert.strictEqual(SK.offRows(b, 'В-02')[0].id, a.id); assert.strictEqual(SK.offRows(b, '1200 x 600')[0].id, a.id);
const reload = SK.fix(MB.fix(JSON.parse(JSON.stringify(b)))), saved = reload.stock.offcuts.find(x => x.id === a.id);
assert.strictEqual(saved.originOrder, origin.id); assert.strictEqual(saved.res, target.id); assert.strictEqual(SK.offCell(reload, saved), 'В-02');
SK.unreserveOrder(reload, target.id); assert.strictEqual(saved.res, undefined); assert.strictEqual(saved.originOrder, origin.id);
MB.useOffcut(reload, saved.id, 'Заказ 158'); assert.strictEqual(SK.reserveOff(reload, saved.id, target), false); assert.strictEqual(SK.offRows(reload, '142').length, 0);
assert.ok(SK.history(b).some(h => h.offcut === a.id && /перемещён/.test(h.title)));
const legacy = MB.addOffcut(b, mat.id, 500, 300, 1, { project: 'Заказ 120' }); SK.setCell(b, mat.id, 'А-01');
assert.strictEqual(SK.offCell(b, legacy), 'А-01'); SK.setOffCell(b, legacy.id, ''); assert.strictEqual(SK.offCell(b, legacy), '');
console.log('ошибок нет: свободные запасы, материалы под заказы, происхождение, независимые места, поиск, резерв и сохранение');
