const assert = require('assert'), fs = require('fs'), os = require('os'), path = require('path'), EventEmitter = require('events');
const W = require('../sth_window_state');
const a = { id: 1, workArea: { x: 0, y: 0, width: 1920, height: 1040 } }, b = { id: 2, workArea: { x: -1600, y: 0, width: 1600, height: 860 } };
const state = { bounds: { x: -1500, y: 25, width: 1300, height: 800 }, displayId: 2, maximized: true };
assert.deepStrictEqual(W.restore(state, [a, b], a).bounds, state.bounds);
const moved = W.restore(state, [a], a); assert.ok(moved.bounds.x >= 0 && moved.bounds.y >= 0); assert.strictEqual(moved.maximized, true);
const small = { id: 3, workArea: { x: 0, y: 0, width: 800, height: 600 } };
const fit = W.restore({ bounds: { x: 9000, y: 8000, width: 4000, height: 3000 } }, [small], small);
assert.deepStrictEqual(fit.bounds, small.workArea); assert.strictEqual(fit.minWidth, 800);
assert.strictEqual(W.restore({ bounds: { x: NaN, y: 0, width: -5, height: 0 } }, [a], a).bounds.width, 1440);
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'sth-window-')), file = path.join(dir, 'window-state.json');
const win = new EventEmitter(); let minimized = false;
Object.assign(win, { getNormalBounds: () => state.bounds, isMinimized: () => minimized, isMaximized: () => true, isFullScreen: () => false });
W.track(win, file, { getDisplayMatching: () => b }); win.emit('close');
assert.deepStrictEqual(W.read(file).bounds, state.bounds); assert.strictEqual(W.read(file).displayId, 2); assert.strictEqual(W.read(file).maximized, true);
minimized = true; win.getNormalBounds = () => ({ x: -32000, y: -32000, width: 1, height: 1 }); win.emit('close');
assert.deepStrictEqual(W.read(file).bounds, state.bounds); win.emit('closed');
fs.writeFileSync(file, '{broken'); assert.strictEqual(W.read(file), null);
